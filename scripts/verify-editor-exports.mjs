import assert from "node:assert/strict";
import { createRequire } from "node:module";
import { mkdir, readFile, writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";

const { chromium } = createRequire(import.meta.url)(process.argv[2] || "playwright");
console.log("Launching browser");
const browser = await chromium.launch({ headless: true, ...(process.argv[3] ? { executablePath: process.argv[3] } : {}) });
console.log("Browser launched");
const directory = new URL("../doc/自定义导出文件名/evidence/", import.meta.url);
const ruleDirectory = new URL("../doc/规则表连续滚动/evidence/", import.meta.url);
await mkdir(directory, { recursive: true });
await mkdir(ruleDirectory, { recursive: true });
let page;
try {
  page = await browser.newPage({ viewport: { width: 1440, height: 1000 }, acceptDownloads: true });
  page.setDefaultTimeout(10000);
  page.setDefaultNavigationTimeout(15000);
  console.log("Page created");
  const errors = [], downloads = [];
  page.on("pageerror", error => errors.push(error.message));
  page.on("download", download => downloads.push(download.suggestedFilename()));
  await page.goto("http://127.0.0.1:5173/turing-machine-simulator/");
  const setSource = source => page.evaluate(value => {
    const editor = document.querySelector("#rules");
    editor.value = value;
    editor.dispatchEvent(new Event("input", { bubbles: true }));
  }, source);
  const source = Array.from({ length: 219 }, (_, i) => `q${i},1->${i === 218 ? "HALT" : `q${i + 1}`},1,R`).join("\n");
  await setSource(source);
  console.log("Source entered");
  await page.click("#compiledProgram summary");
  await page.waitForFunction(() => document.querySelector("#compiledRuleSource").value.split("\n").length === 219);
  const compare = () => page.evaluate(() => {
    const lines = document.querySelector("#compiledRuleSource").value.split("\n");
    const rows = [...document.querySelectorAll(".rule-data-row")];
    const mismatches = rows.filter((row, index) => {
      const f = [...row.querySelectorAll("input,select")].map(field => field.value);
      return Number(row.dataset.index) !== index || `${f[0]},${f[1]}->${f[2]},${f[3]},${f[4]}` !== lines[index];
    });
    return { rows: rows.length, actual: lines.length, mismatches: mismatches.length, pagers: document.querySelectorAll("#rulePrev,#ruleNext").length };
  });
  assert.deepEqual(await compare(), { rows: 219, actual: 219, mismatches: 0, pagers: 0 });
  console.log("219 rows matched");
  await page.getByLabel("规则 219 写入符号", { exact: true }).fill("2");
  await page.getByLabel("规则 219 写入符号", { exact: true }).press("Tab");
  await page.waitForFunction(() => document.querySelector("#rules").value.endsWith("q218,1 -> HALT,2,R") || /q218,1\s*->\s*HALT,2,R$/.test(document.querySelector("#rules").value));
  console.log("Last rule edited");
  await page.locator(".rule-data-row").last().scrollIntoViewIfNeeded();
  const scroll = await page.evaluate(() => {
    const host = document.querySelector("#ruleTable"), last = host.querySelector(".rule-data-row:last-child"), header = host.querySelector(".rule-head");
    return { scrolled: host.scrollTop > 0, lastVisible: last.getBoundingClientRect().bottom <= host.getBoundingClientRect().bottom + 1, sticky: Math.abs(header.getBoundingClientRect().top - host.getBoundingClientRect().top) <= 2 };
  });
  assert.deepEqual(scroll, { scrolled: true, lastVisible: true, sticky: true });
  await page.getByRole("button", { name: "删除规则 219", exact: true }).click();
  assert.equal(await page.locator(".rule-data-row").count(), 218);
  await setSource("bad,rule");
  assert.match(await page.textContent("#ruleCount"), /待修正/);
  await setSource(source);
  assert.equal(await page.locator(".rule-data-row").count(), 219);
  console.log("Deletion and recovery passed");
  const body = source.replaceAll("HALT", "end").split("\n").map(line => `    ${line}`).join("\n");
  await setSource(`bulk(q0,end):\n${body}\nbulk\nbulk`);
  const functions = await compare();
  assert.ok(functions.rows > 219);
  assert.equal(functions.rows, functions.actual);
  assert.equal(functions.mismatches, 0);
  assert.equal(await page.locator(".rule-data-row input:enabled").count(), 0);
  const ruleReport = { flat: { rows: 219, mismatches: 0, pagers: 0 }, scroll, lastRuleEdit: true, lastRuleDelete: true, invalidSourceRecovery: true, functions, functionsReadonly: true };
  await writeFile(new URL("browser.json", ruleDirectory), JSON.stringify(ruleReport, null, 2) + "\n");
  console.log("Rule-table checks passed");

  await setSource(source);
  await page.click("#exportProject");
  assert.equal(await page.locator("#downloadName").evaluate(element => element === document.activeElement), true);
  await page.fill("#downloadName", " ");
  await page.getByRole("button", { name: "下载", exact: true }).click();
  assert.match(await page.textContent("#downloadError"), /请输入/);
  await page.fill("#downloadName", "folder/name");
  await page.getByRole("button", { name: "下载", exact: true }).click();
  assert.match(await page.textContent("#downloadError"), /不能包含/);
  await page.fill("#downloadName", "我的图灵机");
  await page.screenshot({ path: fileURLToPath(new URL("dialog.png", directory)) });
  let pending = page.waitForEvent("download");
  await page.locator("#downloadName").press("Enter");
  const projectDownload = await pending;
  console.log("Project download received", projectDownload.suggestedFilename());
  assert.equal(projectDownload.suggestedFilename(), "我的图灵机.json");
  const project = JSON.parse(await readFile(await projectDownload.path(), "utf8"));
  assert.equal(project.rules, source);
  console.log("Project content verified");
  await page.click("#exportProject");
  await page.click("#cancelDownload");
  assert.equal(await page.locator("dialog").count(), 0);
  await page.click("#exportProject");
  await page.keyboard.press("Escape");
  assert.equal(await page.locator("dialog").count(), 0);
  await page.click("#apply");
  await page.click("#step");
  await page.click("#exportLog");
  await page.fill("#downloadName", "执行记录.CSV");
  pending = page.waitForEvent("download");
  await page.getByRole("button", { name: "下载", exact: true }).click();
  const logDownload = await pending;
  console.log("Log download received", logDownload.suggestedFilename());
  assert.equal(logDownload.suggestedFilename(), "执行记录.CSV");
  const log = await readFile(await logDownload.path(), "utf8");
  assert.match(log, /^step,from,read,to,write,direction,headBefore,headAfter\n1,"q0","1","q1","1","R",0,1$/);
  await page.setViewportSize({ width: 360, height: 700 });
  await page.click("#exportProject");
  const fits = await page.locator("dialog").evaluate(element => { const r = element.getBoundingClientRect(); return r.left >= 0 && r.right <= innerWidth && r.top >= 0 && r.bottom <= innerHeight; });
  assert.equal(fits, true);
  await page.keyboard.press("Escape");
  assert.deepEqual(downloads, ["我的图灵机.json", "执行记录.CSV"]);
  assert.deepEqual(errors, []);
  const report = { projectName: projectDownload.suggestedFilename(), projectContentMatches: true, logName: logDownload.suggestedFilename(), logContentMatches: true, emptyAndInvalidNameRejected: true, cancelAndEscapeNoDownload: true, enterSubmits: true, inputFocused: true, mobileFits: fits, downloads, errors };
  await writeFile(new URL("browser.json", directory), JSON.stringify(report, null, 2) + "\n");
  console.log(JSON.stringify({ ruleTable: ruleReport, export: report }, null, 2));
} catch (error) {
  console.log(await page?.evaluate(() => ({ dialogs: [...document.querySelectorAll("dialog")].map(x => x.outerHTML), rules: document.querySelector("#rules")?.outerHTML, rect: document.querySelector("#rules")?.getBoundingClientRect().toJSON(), focused: document.activeElement?.outerHTML })));
  await page?.screenshot({ path: fileURLToPath(new URL("failure.png", directory)) });
  throw error;
} finally { await browser.close(); }
