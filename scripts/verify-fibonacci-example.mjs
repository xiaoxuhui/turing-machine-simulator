import assert from "node:assert/strict";
import { createRequire } from "node:module";
import { mkdir, writeFile } from "node:fs/promises";

const { chromium } = createRequire(import.meta.url)(process.argv[2] || "playwright");
const browser = await chromium.launch({ headless: true, ...(process.argv[3] ? { executablePath: process.argv[3] } : {}) });
try {
  const page = await browser.newPage();
  const errors = [];
  page.on("pageerror", error => errors.push(error.message));
  await page.goto(process.argv[4] || "http://127.0.0.1:5173/turing-machine-simulator/");
  await page.waitForSelector('#example option[value="fibonacci"]', { state: "attached" });
  assert.equal(await page.locator("#example option").count(), 29);
  const before = await page.inputValue("#rules");
  await page.selectOption("#example", "fibonacci");
  assert.equal(await page.inputValue("#rules"), before, "selecting only previews the example");
  await page.selectOption("#exampleSourceStyle", "commented");
  await page.click("#loadExample");
  assert.equal(await page.inputValue("#initialState"), "fib.seedFirst");
  assert.equal(await page.inputValue("#blankSymbol"), "0");
  assert.equal(await page.inputValue("#input"), "");
  for (const id of ["acceptStates", "rejectStates", "haltStates"]) assert.equal(await page.inputValue(`#${id}`), "");
  assert.equal(await page.isChecked("#unlimitedSteps"), true);
  assert.equal(await page.locator("#errors").textContent(), "");
  const commented = await page.inputValue("#rules");
  const lines = commented.split("\n"), first = lines.findIndex(line => line.includes("->"));
  const phaseNotes = lines.slice(first + 1).filter(line => line.startsWith("#")).length;
  assert.ok(phaseNotes >= 8);
  assert.equal(lines.filter(line => !line.startsWith("#") && line.includes("->")).length, 54);
  for (let i = 0; i < 3; i++) await page.click("#step");
  assert.equal(await page.locator("#stepCount").textContent(), "3");
  assert.equal(await page.locator("#currentState").textContent(), "fib.backToFirst");
  await page.selectOption("#exampleSourceStyle", "plain");
  assert.equal(await page.inputValue("#rules"), commented, "style selection preserves current editor");
  await page.click("#loadExample");
  const plain = await page.inputValue("#rules");
  assert.doesNotMatch(plain, /^\s*#/m);
  assert.equal(plain, commented.split("\n").filter(line => !line.trimStart().startsWith("#")).join("\n"));
  await page.fill("#routeSteps", "10000");
  await page.click("#generateRoute");
  await page.waitForFunction(() => /已显示|后台生成失败/.test(document.querySelector("#routeStatus").textContent));
  const route = await page.locator("#routeStatus").textContent();
  assert.match(route, /已显示/);
  assert.equal(await page.locator("#stepCount").textContent(), "0", "background route leaves main machine intact");
  await page.reload();
  assert.equal(await page.inputValue("#rules"), plain);
  assert.equal(await page.inputValue("#initialState"), "fib.seedFirst");
  assert.equal(await page.isChecked("#unlimitedSteps"), true);
  assert.deepEqual(errors, []);
  const result = { example: "fibonacci", examples: 29, initialState: "fib.seedFirst", blankSymbol: "0", input: "", unlimited: true, rules: 54, phaseNotes, manualSteps: 3, route, preservedAfterReload: true, pageErrors: errors };
  const directory = new URL("../doc/斐波那契示例/evidence/", import.meta.url);
  await mkdir(directory, { recursive: true });
  await writeFile(new URL("browser.json", directory), JSON.stringify(result, null, 2) + "\n");
  console.log(JSON.stringify(result, null, 2));
} finally { await browser.close(); }
