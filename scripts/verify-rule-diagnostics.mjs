import assert from "node:assert/strict";
import { createRequire } from "node:module";
import { mkdir, writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";

const { chromium } = createRequire(import.meta.url)(process.argv[2] || "playwright");
const browser = await chromium.launch({ headless: true, ...(process.argv[3] ? { executablePath: process.argv[3] } : {}) });
const directory = new URL("../doc/规则错误定位/evidence/", import.meta.url);
await mkdir(directory, { recursive: true });
try {
  const page = await browser.newPage({ viewport: { width: 1440, height: 1000 } });
  const pageErrors = [];
  page.on("pageerror", error => pageErrors.push(error.message));
  await page.goto("http://127.0.0.1:5173/turing-machine-simulator/");
  const source = Array.from({ length: 99 }, (_, i) => `# 第 ${i + 1} 行`).join("\n") + "\nq0,l->q1,l.L";
  await page.fill("#rules", source);
  const button = page.locator('#rules-diagnostics button[data-line="100"]');
  assert.match(await button.textContent(), /逗号/);
  assert.equal(await page.locator('.rule-error-line[data-line="100"]').count(), 1);
  await button.click();
  const selected = await page.locator("#rules").evaluate(editor => editor.value.slice(editor.selectionStart, editor.selectionEnd));
  assert.equal(selected, "q0,l->q1,l.L");
  await page.locator(".rule-editor-frame").screenshot({ path: fileURLToPath(new URL("line-100.png", directory)) });
  const highlighted = await page.locator('.rule-error-line[data-line="100"]').evaluate(mark => ({ top: parseFloat(mark.style.top), color: getComputedStyle(mark).backgroundColor, height: mark.getBoundingClientRect().height }));
  assert.ok(highlighted.top >= 0 && highlighted.top < await page.locator("#rules").evaluate(editor => editor.clientHeight));
  assert.match(highlighted.color, /239, 68, 68/);
  await page.locator("#rules").evaluate(editor => { editor.scrollTop = 0; editor.style.height = "300px"; editor.dispatchEvent(new Event("scroll")); });
  assert.ok(await page.locator('.rule-error-line[data-line="100"]').evaluate(mark => parseFloat(mark.style.top)) > 1000);
  await page.fill("#rules", source.replace("l.L", "l,L"));
  assert.equal(await page.locator(".rule-error-line").count(), 0);
  assert.equal(await page.getAttribute("#rules", "aria-invalid"), "false");
  assert.equal(await page.locator("#rules-diagnostics").isHidden(), true);
  assert.equal(await page.locator("#errors").textContent(), "");
  await page.fill("#rules", "q0,0->HALT,1,N");
  await page.locator("#rules").evaluate(editor => { editor.focus(); editor.setSelectionRange(2, 3); });
  await page.keyboard.press("Delete");
  await page.keyboard.type("1");
  assert.equal(await page.getAttribute("#rules", "aria-invalid"), "true");
  assert.equal(await page.locator(".rule-error-line").count(), 1);
  await page.locator("#rules").evaluate(editor => {
    editor.value = "bad"; editor.dispatchEvent(new Event("input", { bubbles: true }));
    editor.value = "q0,0->HALT,1,N"; editor.dispatchEvent(new Event("input", { bubbles: true }));
  });
  assert.equal(await page.locator(".rule-error-line").count(), 0);
  const long = "q".repeat(2000) + ",0->HALT,1,N";
  await page.fill("#rules", long);
  assert.equal(await page.locator("#rules").evaluate(editor => editor.wrap), "off");
  await page.setViewportSize({ width: 390, height: 844 });
  assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth));
  await page.goto("http://127.0.0.1:5173/turing-machine-simulator/campaign.html");
  await page.fill("#rulesEditor", "q0,□->HALT,1.L");
  assert.equal(await page.locator('.rule-error-line[data-line="1"]').count(), 1);
  assert.match(await page.locator("#rulesEditor-diagnostics").textContent(), /逗号/);
  await page.fill("#rulesEditor", "q0,□->HALT,1,N");
  assert.equal(await page.locator(".rule-error-line").count(), 0);
  assert.equal(await page.locator("#editorError").textContent(), "");
  assert.deepEqual(pageErrors, []);
  const result = { selected, highlighted, scrollAndResize: true, clearsAfterCorrection: true, fastInvalidEditMarked: true, sameFrameCorrectionClears: true, longLineNoWrap: true, mobileNoOverflow: true, campaign: true, pageErrors };
  await writeFile(new URL("browser.json", directory), JSON.stringify(result, null, 2) + "\n");
  console.log(JSON.stringify(result, null, 2));
} finally { await browser.close(); }
